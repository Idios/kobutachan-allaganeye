@pytest.mark.parametrize(
    "location", cvc.VERSION_LOCATIONS, ids=[loc.path for loc in cvc.VERSION_LOCATIONS]
)
def test_each_location_mismatch_returns_1(
    tmp_path: Path, location: Any, capsys: pytest.CaptureFixture[str]
) -> None:
    """全箇所のいずれか 1 つがズレただけで exit 1 になること (箇所ごとの発火実証)。

    `::error::` 行のうち **注入した値 9.9.9 を報告している行** に当該 path が
    含まれることまで検査する (単に path が出力に現れるだけでは発火の証拠にならない)。
    """
    _write_synthetic_repo(tmp_path, "1.2.3")
    _set_version_at(tmp_path, location, "9.9.9")

    rc = cvc.main(["--repo-root", str(tmp_path)])
    errors = _error_lines(capsys.readouterr().out)

    assert rc == 1
    assert isinstance(location, cvc.VersionLocation)
    offending = [line for line in errors if '"9.9.9"' in line]
    assert offending, f"注入した 9.9.9 を報告する ::error:: 行がない: {errors}"
    assert all(location.path in line for line in offending)


def test_package_lock_nested_field_mismatch_returns_1(tmp_path: Path) -> None:
    """package-lock.json の `packages[""].version` だけのズレも検知すること。

    npm は root `version` と `packages[""].version` の双方を持つため、片方だけが
    古びる drift が実在する。
    """
    _write_synthetic_repo(tmp_path, "1.2.3")
    lock = tmp_path / "gui" / "package-lock.json"
    data = json.loads(lock.read_text(encoding="utf-8"))
    data["packages"][""]["version"] = "9.9.9"
    lock.write_text(json.dumps(data), encoding="utf-8")

    assert cvc.main(["--repo-root", str(tmp_path)]) == 1


def test_cargo_lock_ignores_lockfile_format_and_dependency_versions(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Cargo.lock は allaganeye-gui の `[[package]]` だけを見ること。

    素朴に「`version = ` 行」を拾う実装だと、root の lockfile フォーマット版
    (`version = 4`) や依存クレートの version (serde 1.0.0) を掴んでしまい、
    バンプしていないのに毎回 fail する / あるいは無関係な値で比較する。
    合成 repo は両方を仕込んであるので、ここが 0 で通ること自体が証拠になる。
    """
    _write_synthetic_repo(tmp_path, "1.2.3")

    assert cvc.main(["--repo-root", str(tmp_path)]) == 0

    out = capsys.readouterr().out
    assert "gui/src-tauri/Cargo.lock" in out
    assert "4" not in _versions_in(out, "gui/src-tauri/Cargo.lock")
    assert _versions_in(out, "gui/src-tauri/Cargo.lock") == ["1.2.3"]


def test_cargo_lock_missing_package_entry_returns_2(tmp_path: Path) -> None:
    """パッケージ名が変わって `[[package]]` を特定できないときは exit 2 に倒すこと。

    「見つからないので検査しない」を 0 で通すと、ガードが無いより有害になる。
    """
    _write_synthetic_repo(tmp_path, "1.2.3")
    lock = tmp_path / "gui" / "src-tauri" / "Cargo.lock"
    lock.write_text(
        lock.read_text(encoding="utf-8").replace(
            'name = "allaganeye-gui"', 'name = "allaganeye-gui-renamed"'
        ),
        encoding="utf-8",
    )

    assert cvc.main(["--repo-root", str(tmp_path)]) == 2


