"""Tests for scripts/check_version_consistency.py (#911).

保護機構は不発でも green になるため、本テストは **違反を注入して exit code の
生値を観測する** 形で書く。正常系だけを見て「ガードがある」と判断しない。
"""

from __future__ import annotations

import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPTS_DIR = REPO_ROOT / "scripts"

_spec = importlib.util.spec_from_file_location(
    "check_version_consistency", SCRIPTS_DIR / "check_version_consistency.py"
)
assert _spec is not None and _spec.loader is not None
cvc = importlib.util.module_from_spec(_spec)
# @dataclass は解決時に sys.modules[cls.__module__] を引くため、exec_module の前に
# 登録しておかないと AttributeError になる。
sys.modules[_spec.name] = cvc
_spec.loader.exec_module(cvc)


def _write_synthetic_repo(root: Path, version: str = "1.2.3") -> None:
    """全バージョン保持箇所が `version` で一致した合成 repo を作る。"""
    (root / "gui" / "src-tauri").mkdir(parents=True, exist_ok=True)

    (root / "pyproject.toml").write_text(
        f'[project]\nname = "allaganeye"\nversion = "{version}"\n', encoding="utf-8"
    )
    (root / "gui" / "src-tauri" / "Cargo.toml").write_text(
        f'[package]\nname = "allaganeye-gui"\nversion = "{version}"\nedition = "2021"\n',
        encoding="utf-8",
    )
    (root / "gui" / "package.json").write_text(
        json.dumps({"name": "allaganeye-gui", "version": version}), encoding="utf-8"
    )
    (root / "gui" / "package-lock.json").write_text(
        json.dumps(
            {
                "name": "allaganeye-gui",
                "version": version,
                "packages": {"": {"name": "allaganeye-gui", "version": version}},
            }
        ),
        encoding="utf-8",
    )
    (root / "gui" / "src-tauri" / "tauri.conf.json").write_text(
        json.dumps({"productName": "allaganeye-gui", "version": version}),
        encoding="utf-8",
    )
    # Cargo.lock は実物の構造を再現する。落とし穴が 2 つあるため:
    #   1. root 直下の `version = 4` は lockfile フォーマット版であってリリース
    #      バージョンではない
    #   2. 依存クレートも `[[package]]` として同じ形で並ぶ (ここでは serde 1.0.0)
    # どちらも拾ってはいけない。
    (root / "gui" / "src-tauri" / "Cargo.lock").write_text(
        "# This file is automatically @generated by Cargo.\n"
        "version = 4\n"
        "\n"
        '[[package]]\nname = "serde"\nversion = "1.0.0"\n'
        'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
        "\n"
        f'[[package]]\nname = "allaganeye-gui"\nversion = "{version}"\n'
        'dependencies = [\n "serde",\n]\n',
        encoding="utf-8",
    )


def _error_lines(captured: str) -> list[str]:
    """`::error::` 注釈行だけを抜き出す。

    スクリプトは常に全箇所の一覧を stdout に出すため、出力全体に対して path の
    存在を assert すると「ガードが発火していなくても通る」vacuous green になる。
    発火の証拠は `::error::` 行に限定して観測する。
    """
    return [line for line in captured.splitlines() if line.startswith("::error::")]


def _versions_in(captured: str, path: str) -> list[str]:
    """一覧行 (`<path> (<field>): <version>`) から `path` 由来の値だけを抜き出す。"""
    return [
        line.rsplit(": ", 1)[1]
        for line in captured.splitlines()
        if line.startswith(f"{path} (")
    ]


def _set_version_at(root: Path, location: Any, version: str) -> None:
    """`location` が指す箇所のバージョンだけを差し替える。

    `cvc` は importlib で動的ロードした module なので `VersionLocation` を静的型と
    しては参照できない。型は `Any` にし、実体の検査は実行時の `isinstance` で行う。
    """
    assert isinstance(location, cvc.VersionLocation)
    path = root / location.path
    if location.fmt == "json":
        data = json.loads(path.read_text(encoding="utf-8"))
        for keys in location.keys:
            node = data
            for key in keys[:-1]:
                node = node[key]
            node[keys[-1]] = version
        path.write_text(json.dumps(data), encoding="utf-8")
    elif location.select is not None:
        # Cargo.lock は該当 [[package]] ブロックの version 行だけを差し替える
        # (root の `version = 4` や依存クレートの version を巻き込まない)。
        _, field, expected = location.select
        text = path.read_text(encoding="utf-8")
        text, replaced = re.subn(
            rf'(^{field} = "{re.escape(expected)}"\n)version = ".*"$',
            rf'\g<1>version = "{version}"',
            text,
            flags=re.M,
        )
        assert replaced == 1, (
            f"{location.path}: 差し替え対象が {replaced} 件 (1 件のはず)"
        )
        path.write_text(text, encoding="utf-8")
    else:
        text = path.read_text(encoding="utf-8")
        path.write_text(
            re.sub(r'^version = ".*"$', f'version = "{version}"', text, flags=re.M),
            encoding="utf-8",
        )


