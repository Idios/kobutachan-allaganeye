def test_mismatch_reports_every_offending_location(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """複数箇所がズレたとき、最初の 1 件で打ち切らず全件報告すること。"""
    _write_synthetic_repo(tmp_path, "1.2.3")
    _set_version_at(tmp_path, cvc.VERSION_LOCATIONS[1], "9.9.9")
    _set_version_at(tmp_path, cvc.VERSION_LOCATIONS[2], "8.8.8")

    rc = cvc.main(["--repo-root", str(tmp_path)])
    errors = _error_lines(capsys.readouterr().out)

    assert rc == 1
    assert any(
        '"9.9.9"' in line and cvc.VERSION_LOCATIONS[1].path in line for line in errors
    )
    assert any(
        '"8.8.8"' in line and cvc.VERSION_LOCATIONS[2].path in line for line in errors
    )


